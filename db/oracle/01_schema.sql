--------------------------------------------------------------------------------
-- CargoVerse logistics database — schema (Oracle Database 19c / 21c / 23ai)
-- Run as the application schema owner (e.g. WARETRACK). Order of scripts:
--   00_create_user.sql (as SYSTEM, optional)  01_schema.sql  02_plsql.sql
--   03_views.sql  04_seed.sql  05_reports.sql (sample queries)
-- 99_drop_all.sql removes everything.
--------------------------------------------------------------------------------
SET DEFINE OFF

-- ============================================================================
-- 1. Security: roles, permissions, job titles
-- ============================================================================
CREATE TABLE roles (
  role_code     VARCHAR2(20)  CONSTRAINT pk_roles PRIMARY KEY,
  role_name     VARCHAR2(60)  NOT NULL,
  description   VARCHAR2(400),
  CONSTRAINT ck_roles_code CHECK (role_code IN ('ADMIN', 'MANAGER', 'OPERATOR'))
);

CREATE TABLE permissions (
  perm_code     VARCHAR2(40)  CONSTRAINT pk_permissions PRIMARY KEY,
  description   VARCHAR2(400) NOT NULL
);

CREATE TABLE role_permissions (
  role_code     VARCHAR2(20)  NOT NULL CONSTRAINT fk_rp_role REFERENCES roles (role_code),
  perm_code     VARCHAR2(40)  NOT NULL CONSTRAINT fk_rp_perm REFERENCES permissions (perm_code),
  CONSTRAINT pk_role_permissions PRIMARY KEY (role_code, perm_code)
);

CREATE TABLE job_titles (
  job_code          VARCHAR2(30)   CONSTRAINT pk_job_titles PRIMARY KEY,
  title             VARCHAR2(80)   NOT NULL CONSTRAINT uq_job_title UNIQUE,
  responsibilities  VARCHAR2(1000)
);

-- ============================================================================
-- 2. Facilities and people
-- ============================================================================
CREATE TABLE facilities (
  facility_id           VARCHAR2(10)  CONSTRAINT pk_facilities PRIMARY KEY,
  name                  VARCHAR2(80)  NOT NULL CONSTRAINT uq_facility_name UNIQUE,
  short_name            VARCHAR2(40)  NOT NULL,
  facility_kind         VARCHAR2(30)  NOT NULL,
  address               VARCHAR2(200) NOT NULL,
  capacity_pallets      NUMBER(8)     NOT NULL,
  stock_pallets         NUMBER(8)     DEFAULT 0 NOT NULL,   -- maintained by trg_stock_movements_ai
  stock_start_pallets   NUMBER(8)     DEFAULT 0 NOT NULL,   -- stock at shift start (for the delta KPI)
  outbound_today        NUMBER(6)     DEFAULT 0 NOT NULL,
  putaways_today        NUMBER(6)     DEFAULT 0 NOT NULL,
  otd_prev_pct          NUMBER(5,2)   DEFAULT 0 NOT NULL,   -- on-time % of the previous period
  trucks_on_site_start  NUMBER(4)     DEFAULT 0 NOT NULL,
  imports_today         NUMBER(6)     DEFAULT 0 NOT NULL,   -- trucks that brought goods in (trg_gate_log_ai)
  import_pallets_today  NUMBER(8)     DEFAULT 0 NOT NULL,
  exports_today         NUMBER(6)     DEFAULT 0 NOT NULL,   -- trucks that took goods out (trg_gate_log_ai)
  export_pallets_today  NUMBER(8)     DEFAULT 0 NOT NULL,
  CONSTRAINT ck_fac_kind     CHECK (facility_kind IN ('Depot', 'Cross-dock', 'Distribution center')),
  CONSTRAINT ck_fac_capacity CHECK (capacity_pallets > 0),
  CONSTRAINT ck_fac_stock    CHECK (stock_pallets >= 0),
  CONSTRAINT ck_fac_otd      CHECK (otd_prev_pct BETWEEN 0 AND 100)
);

CREATE TABLE employees (
  employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_employees PRIMARY KEY,
  full_name     VARCHAR2(80)  NOT NULL,
  email         VARCHAR2(120) NOT NULL CONSTRAINT uq_emp_email UNIQUE,
  phone         VARCHAR2(30),
  job_code      VARCHAR2(30)  NOT NULL CONSTRAINT fk_emp_job REFERENCES job_titles (job_code),
  facility_id   VARCHAR2(10)  CONSTRAINT fk_emp_facility REFERENCES facilities (facility_id),
  hired_on      DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  emp_status    VARCHAR2(12)  DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT ck_emp_status CHECK (emp_status IN ('ACTIVE', 'ON_LEAVE', 'INACTIVE')),
  CONSTRAINT ck_emp_email  CHECK (email LIKE '%_@_%._%')
);
CREATE INDEX ix_emp_facility ON employees (facility_id);

CREATE TABLE app_users (
  user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_app_users PRIMARY KEY,
  username        VARCHAR2(40)  NOT NULL CONSTRAINT uq_username UNIQUE,
  password_hash   VARCHAR2(200) NOT NULL,
  role_code       VARCHAR2(20)  NOT NULL CONSTRAINT fk_user_role REFERENCES roles (role_code),
  employee_id     NUMBER        NOT NULL CONSTRAINT uq_user_employee UNIQUE
                                CONSTRAINT fk_user_employee REFERENCES employees (employee_id),
  is_active       CHAR(1)       DEFAULT 'Y' NOT NULL,
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  created_by      NUMBER        CONSTRAINT fk_user_creator REFERENCES app_users (user_id),
  last_login_at   TIMESTAMP,
  failed_logins   NUMBER(3)     DEFAULT 0 NOT NULL,
  CONSTRAINT ck_user_active   CHECK (is_active IN ('Y', 'N')),
  CONSTRAINT ck_user_lower    CHECK (username = LOWER(username)),
  CONSTRAINT ck_user_hash     CHECK (password_hash LIKE 'scrypt$%')
);

-- Which facilities a user may work with (admins are granted all by permission).
CREATE TABLE user_facility_access (
  user_id       NUMBER       NOT NULL CONSTRAINT fk_ufa_user REFERENCES app_users (user_id) ON DELETE CASCADE,
  facility_id   VARCHAR2(10) NOT NULL CONSTRAINT fk_ufa_facility REFERENCES facilities (facility_id),
  granted_at    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_user_facility_access PRIMARY KEY (user_id, facility_id)
);

-- Login sessions ("remember me" sessions last 30 days and are renewed on use).
CREATE TABLE user_sessions (
  session_id    VARCHAR2(64)  CONSTRAINT pk_user_sessions PRIMARY KEY,
  user_id       NUMBER        NOT NULL CONSTRAINT fk_sess_user REFERENCES app_users (user_id) ON DELETE CASCADE,
  created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  last_seen_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at    TIMESTAMP     NOT NULL,
  revoked       CHAR(1)       DEFAULT 'N' NOT NULL,
  remember_me   CHAR(1)       DEFAULT 'N' NOT NULL,
  user_agent    VARCHAR2(200),
  CONSTRAINT ck_sess_revoked  CHECK (revoked IN ('Y', 'N')),
  CONSTRAINT ck_sess_remember CHECK (remember_me IN ('Y', 'N'))
);
CREATE INDEX ix_sess_user ON user_sessions (user_id);

-- ============================================================================
-- 3. Logistics master data
-- ============================================================================
CREATE TABLE carriers (
  carrier_id    VARCHAR2(20)  CONSTRAINT pk_carriers PRIMARY KEY,
  name          VARCHAR2(60)  NOT NULL CONSTRAINT uq_carrier_name UNIQUE,
  display_name  VARCHAR2(80)  NOT NULL,
  phone         VARCHAR2(30)
);

CREATE TABLE drivers (
  driver_id     NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_drivers PRIMARY KEY,
  carrier_id    VARCHAR2(20)  NOT NULL CONSTRAINT fk_driver_carrier REFERENCES carriers (carrier_id),
  full_name     VARCHAR2(80)  NOT NULL,
  license_no    VARCHAR2(30)  NOT NULL CONSTRAINT uq_driver_license UNIQUE
);

CREATE TABLE skus (
  sku_id            VARCHAR2(20)  CONSTRAINT pk_skus PRIMARY KEY,
  name              VARCHAR2(80)  NOT NULL,
  category          VARCHAR2(40)  NOT NULL,
  units_per_pallet  NUMBER(6)     NOT NULL,
  kg_per_pallet     NUMBER(8,2)   NOT NULL,
  pallet_look       VARCHAR2(12)  DEFAULT 'cardboard' NOT NULL,
  icon              VARCHAR2(12)  DEFAULT 'box' NOT NULL,
  CONSTRAINT ck_sku_units CHECK (units_per_pallet > 0),
  CONSTRAINT ck_sku_kg    CHECK (kg_per_pallet > 0),
  CONSTRAINT ck_sku_look  CHECK (pallet_look IN ('cardboard', 'blue', 'white'))
);

CREATE TABLE inventory (
  facility_id     VARCHAR2(10) NOT NULL CONSTRAINT fk_inv_facility REFERENCES facilities (facility_id),
  sku_id          VARCHAR2(20) NOT NULL CONSTRAINT fk_inv_sku REFERENCES skus (sku_id),
  units           NUMBER(10)   DEFAULT 0 NOT NULL,      -- maintained by trg_stock_movements_ai
  reorder_level   NUMBER(10)   DEFAULT 0 NOT NULL,
  display_order   NUMBER(3)    DEFAULT 0 NOT NULL,
  CONSTRAINT pk_inventory PRIMARY KEY (facility_id, sku_id),
  CONSTRAINT ck_inv_units CHECK (units >= 0),
  CONSTRAINT ck_inv_reorder CHECK (reorder_level >= 0)
);

CREATE TABLE docks (
  dock_id       VARCHAR2(20)  CONSTRAINT pk_docks PRIMARY KEY,
  facility_id   VARCHAR2(10)  NOT NULL CONSTRAINT fk_dock_facility REFERENCES facilities (facility_id),
  dock_name     VARCHAR2(20)  NOT NULL,
  dock_kind     VARCHAR2(4)   NOT NULL,
  description   VARCHAR2(120),
  truck_id      VARCHAR2(20),                       -- booked/occupying truck (FK added below)
  trucks_today  NUMBER(4)     DEFAULT 0 NOT NULL,
  CONSTRAINT uq_dock_name UNIQUE (facility_id, dock_name),
  CONSTRAINT ck_dock_kind CHECK (dock_kind IN ('IN', 'OUT', 'ANY'))
);

CREATE TABLE chargers (
  charger_id      VARCHAR2(20)  CONSTRAINT pk_chargers PRIMARY KEY,
  facility_id     VARCHAR2(10)  NOT NULL CONSTRAINT fk_chg_facility REFERENCES facilities (facility_id),
  description     VARCHAR2(120) NOT NULL,
  sessions_today  NUMBER(5)     DEFAULT 0 NOT NULL,
  energy_kwh      NUMBER(9,2)   DEFAULT 0 NOT NULL,
  rate_pct_min    NUMBER(5,2)   NOT NULL
);

-- ============================================================================
-- 4. Fleet: trucks, shipments, forklifts, pallets
-- ============================================================================
CREATE TABLE trucks (
  truck_id             VARCHAR2(20)  CONSTRAINT pk_trucks PRIMARY KEY,
  carrier_id           VARCHAR2(20)  NOT NULL CONSTRAINT fk_truck_carrier REFERENCES carriers (carrier_id),
  driver_id            NUMBER        NOT NULL CONSTRAINT fk_truck_driver REFERENCES drivers (driver_id),
  plate                VARCHAR2(20)  NOT NULL CONSTRAINT uq_truck_plate UNIQUE,
  facility_id          VARCHAR2(10)  NOT NULL CONSTRAINT fk_truck_facility REFERENCES facilities (facility_id),
  direction            VARCHAR2(8)   NOT NULL,
  capacity_pallets     NUMBER(3)     NOT NULL,
  cargo_pallets        NUMBER(3)     DEFAULT 0 NOT NULL,
  status               VARCHAR2(12)  NOT NULL,
  dock_id              VARCHAR2(20)  CONSTRAINT fk_truck_dock REFERENCES docks (dock_id),
  current_shipment_id  VARCHAR2(20),                -- FK added below
  sku_id               VARCHAR2(20)  NOT NULL CONSTRAINT fk_truck_sku REFERENCES skus (sku_id),
  forklift_id          VARCHAR2(10),                -- assigned forklift, FK added below
  -- live telemetry written by the operations engine
  leg_idx              NUMBER(2)     DEFAULT 0 NOT NULL,
  leg_dist             NUMBER(10,3)  DEFAULT 0 NOT NULL,
  pos_x                NUMBER(10,3)  DEFAULT 0 NOT NULL,
  pos_z                NUMBER(10,3)  DEFAULT 0 NOT NULL,
  heading              NUMBER(10,5)  DEFAULT 0 NOT NULL,
  speed                NUMBER(8,3)   DEFAULT 0 NOT NULL,
  away_remaining_s     NUMBER(10,2)  DEFAULT 0 NOT NULL,
  trade_lane           VARCHAR2(4)   DEFAULT 'ROAD' NOT NULL, -- SEA = this trip is a container to / from the port
  updated_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_truck_lane      CHECK (trade_lane IN ('ROAD', 'SEA')),
  CONSTRAINT ck_truck_direction CHECK (direction IN ('INBOUND', 'OUTBOUND')),
  CONSTRAINT ck_truck_capacity  CHECK (capacity_pallets > 0),
  CONSTRAINT ck_truck_cargo     CHECK (cargo_pallets BETWEEN 0 AND capacity_pallets),
  CONSTRAINT ck_truck_status    CHECK (status IN ('EN_ROUTE', 'AT_GATE', 'DOCKING', 'WORKING', 'READY', 'DEPARTING', 'LEAVING', 'AWAY'))
);
CREATE INDEX ix_truck_facility ON trucks (facility_id, status);

CREATE TABLE shipments (
  shipment_id      VARCHAR2(20)  CONSTRAINT pk_shipments PRIMARY KEY,
  truck_id         VARCHAR2(20)  NOT NULL CONSTRAINT fk_ship_truck REFERENCES trucks (truck_id),
  facility_id      VARCHAR2(10)  NOT NULL CONSTRAINT fk_ship_facility REFERENCES facilities (facility_id),
  direction        VARCHAR2(8)   NOT NULL,
  customer         VARCHAR2(100) NOT NULL,
  destination      VARCHAR2(120) NOT NULL,
  sku_id           VARCHAR2(20)  NOT NULL CONSTRAINT fk_ship_sku REFERENCES skus (sku_id),
  pallets          NUMBER(3)     NOT NULL,
  -- operational clock (seconds since midnight of the operations day)
  confirmed_s      NUMBER(7)     NOT NULL,
  picked_s         NUMBER(7)     NOT NULL,
  loaded_s         NUMBER(7),
  transit_s        NUMBER(7),
  delivered_s      NUMBER(7),
  promised_s       NUMBER(7)     NOT NULL,
  transit_minutes  NUMBER(4)     DEFAULT 0 NOT NULL,
  on_time          CHAR(1),                         -- derived by trg_shipments_biu
  ship_status      VARCHAR2(12)  DEFAULT 'OPEN' NOT NULL, -- derived by trg_shipments_biu
  trade_lane       VARCHAR2(4)   DEFAULT 'ROAD' NOT NULL,  -- SEA = travels in a container through the port
  container_no     VARCHAR2(11),                          -- ISO 6346 container number (sea freight)
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  delivered_ts     TIMESTAMP,
  CONSTRAINT ck_ship_lane      CHECK (trade_lane IN ('ROAD', 'SEA')),
  CONSTRAINT ck_ship_container CHECK ((trade_lane = 'ROAD' AND container_no IS NULL)
                                   OR (trade_lane = 'SEA' AND REGEXP_LIKE(container_no, '^[A-Z]{3}U[0-9]{7}$'))),
  CONSTRAINT ck_ship_direction CHECK (direction IN ('INBOUND', 'OUTBOUND')),
  CONSTRAINT ck_ship_pallets   CHECK (pallets > 0),
  CONSTRAINT ck_ship_on_time   CHECK (on_time IN ('Y', 'N')),
  CONSTRAINT ck_ship_status    CHECK (ship_status IN ('OPEN', 'IN_PROGRESS', 'IN_TRANSIT', 'DELIVERED')),
  CONSTRAINT ck_ship_order     CHECK (picked_s >= 0 AND confirmed_s >= 0)
);
CREATE INDEX ix_ship_facility ON shipments (facility_id, delivered_ts);
CREATE INDEX ix_ship_truck ON shipments (truck_id);

ALTER TABLE trucks ADD CONSTRAINT fk_truck_shipment
  FOREIGN KEY (current_shipment_id) REFERENCES shipments (shipment_id) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE docks ADD CONSTRAINT fk_dock_truck
  FOREIGN KEY (truck_id) REFERENCES trucks (truck_id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE forklifts (
  forklift_id    VARCHAR2(10)  CONSTRAINT pk_forklifts PRIMARY KEY,
  facility_id    VARCHAR2(10)  NOT NULL CONSTRAINT fk_fl_facility REFERENCES facilities (facility_id),
  model          VARCHAR2(60)  NOT NULL,
  operator_id    NUMBER        CONSTRAINT fk_fl_operator REFERENCES employees (employee_id),
  charger_id     VARCHAR2(20)  NOT NULL CONSTRAINT uq_fl_charger UNIQUE
                               CONSTRAINT fk_fl_charger REFERENCES chargers (charger_id),
  battery_pct    NUMBER(5,2)   NOT NULL,
  task_state     VARCHAR2(12)  NOT NULL,
  truck_id       VARCHAR2(20)  CONSTRAINT fk_fl_truck REFERENCES trucks (truck_id) DEFERRABLE INITIALLY DEFERRED,
  pallet_id      VARCHAR2(20),                       -- FK added below
  moves_today    NUMBER(5)     DEFAULT 0 NOT NULL,
  pos_x          NUMBER(10,3)  DEFAULT 0 NOT NULL,
  pos_z          NUMBER(10,3)  DEFAULT 0 NOT NULL,
  heading        NUMBER(10,5)  DEFAULT 0 NOT NULL,
  timer_s        NUMBER(8,3)   DEFAULT 0 NOT NULL,
  pick_json      VARCHAR2(200),
  drop_json      VARCHAR2(200),
  updated_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_fl_battery CHECK (battery_pct BETWEEN 0 AND 100),
  CONSTRAINT ck_fl_state   CHECK (task_state IN ('IDLE', 'CHARGING', 'TO_PICK', 'LIFTING', 'TO_DROP', 'DROPPING', 'TO_HOME')),
  CONSTRAINT ck_fl_pick    CHECK (pick_json IS JSON),
  CONSTRAINT ck_fl_drop    CHECK (drop_json IS JSON)
);
CREATE INDEX ix_fl_facility ON forklifts (facility_id);
CREATE INDEX ix_fl_operator ON forklifts (operator_id);

ALTER TABLE trucks ADD CONSTRAINT fk_truck_forklift
  FOREIGN KEY (forklift_id) REFERENCES forklifts (forklift_id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE pallets (
  pallet_id       VARCHAR2(20)  CONSTRAINT pk_pallets PRIMARY KEY,
  facility_id     VARCHAR2(10)  NOT NULL CONSTRAINT fk_pal_facility REFERENCES facilities (facility_id),
  sku_id          VARCHAR2(20)  NOT NULL CONSTRAINT fk_pal_sku REFERENCES skus (sku_id),
  qty             NUMBER(6)     NOT NULL,
  weight_kg       NUMBER(8,2)   NOT NULL,
  lot_no          VARCHAR2(20)  NOT NULL,
  received_label  VARCHAR2(40)  NOT NULL,
  yard_slot       NUMBER(3),
  forklift_id     VARCHAR2(10)  CONSTRAINT fk_pal_forklift REFERENCES forklifts (forklift_id) DEFERRABLE INITIALLY DEFERRED,
  is_featured     CHAR(1)       DEFAULT 'N' NOT NULL,
  is_reserved     CHAR(1)       DEFAULT 'N' NOT NULL,
  pallet_status   VARCHAR2(12)  GENERATED ALWAYS AS (
                    CASE WHEN yard_slot IS NOT NULL THEN 'STAGED'
                         WHEN forklift_id IS NOT NULL THEN 'IN_TRANSIT'
                         ELSE 'UNPLACED' END) VIRTUAL,
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_pal_qty      CHECK (qty > 0),
  CONSTRAINT ck_pal_place    CHECK (yard_slot IS NULL OR forklift_id IS NULL),
  CONSTRAINT ck_pal_featured CHECK (is_featured IN ('Y', 'N')),
  CONSTRAINT ck_pal_reserved CHECK (is_reserved IN ('Y', 'N'))
);
-- One pallet per yard slot per facility (rows without a slot are not indexed).
CREATE UNIQUE INDEX ux_pallet_slot ON pallets (
  CASE WHEN yard_slot IS NOT NULL THEN facility_id END,
  CASE WHEN yard_slot IS NOT NULL THEN yard_slot END);

ALTER TABLE forklifts ADD CONSTRAINT fk_fl_pallet
  FOREIGN KEY (pallet_id) REFERENCES pallets (pallet_id) DEFERRABLE INITIALLY DEFERRED;

-- Stock ledger: every change to stock is a row here; triggers keep totals in sync.
CREATE TABLE stock_movements (
  movement_id     NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_stock_movements PRIMARY KEY,
  facility_id     VARCHAR2(10)  NOT NULL CONSTRAINT fk_sm_facility REFERENCES facilities (facility_id),
  sku_id          VARCHAR2(20)  CONSTRAINT fk_sm_sku REFERENCES skus (sku_id),
  pallets_delta   NUMBER(8)     NOT NULL,
  units_delta     NUMBER(10)    DEFAULT 0 NOT NULL,
  reason          VARCHAR2(12)  NOT NULL,
  pallet_id       VARCHAR2(20),
  shipment_id     VARCHAR2(20),
  forklift_id     VARCHAR2(10),
  sim_time_s      NUMBER(7),
  created_by      NUMBER        CONSTRAINT fk_sm_user REFERENCES app_users (user_id),
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_sm_reason CHECK (reason IN ('OPENING', 'RECEIPT', 'PUTAWAY', 'PICK', 'RETURN', 'ADJUSTMENT', 'STORE_SHIP'))
);
CREATE INDEX ix_sm_facility ON stock_movements (facility_id, created_at);

-- ============================================================================
-- 5. Work management: tasks assigned to staff, and their status history
-- ============================================================================
CREATE TABLE tasks (
  task_id         NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_tasks PRIMARY KEY,
  facility_id     VARCHAR2(10)   NOT NULL CONSTRAINT fk_task_facility REFERENCES facilities (facility_id),
  title           VARCHAR2(160)  NOT NULL,
  description     VARCHAR2(1000),
  task_type       VARCHAR2(16)   NOT NULL,
  priority        VARCHAR2(8)    DEFAULT 'NORMAL' NOT NULL,
  task_status     VARCHAR2(12)   DEFAULT 'OPEN' NOT NULL,
  source          VARCHAR2(8)    DEFAULT 'MANUAL' NOT NULL,
  assigned_to     NUMBER         CONSTRAINT fk_task_assignee REFERENCES employees (employee_id),
  created_by      NUMBER         CONSTRAINT fk_task_creator REFERENCES app_users (user_id),
  truck_id        VARCHAR2(20)   CONSTRAINT fk_task_truck REFERENCES trucks (truck_id),
  dock_id         VARCHAR2(20)   CONSTRAINT fk_task_dock REFERENCES docks (dock_id),
  forklift_id     VARCHAR2(10)   CONSTRAINT fk_task_forklift REFERENCES forklifts (forklift_id),
  shipment_id     VARCHAR2(20)   CONSTRAINT fk_task_shipment REFERENCES shipments (shipment_id),
  due_at          TIMESTAMP,
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  started_at      TIMESTAMP,
  completed_at    TIMESTAMP,
  CONSTRAINT ck_task_type     CHECK (task_type IN ('UNLOAD', 'LOAD', 'PUTAWAY', 'CYCLE_COUNT', 'MAINTENANCE', 'DOCK_CHECK', 'OTHER')),
  CONSTRAINT ck_task_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
  CONSTRAINT ck_task_status   CHECK (task_status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'BLOCKED', 'DONE', 'CANCELLED')),
  CONSTRAINT ck_task_source   CHECK (source IN ('MANUAL', 'SYSTEM')),
  CONSTRAINT ck_task_assigned CHECK (task_status IN ('OPEN', 'CANCELLED') OR assigned_to IS NOT NULL)
);
CREATE INDEX ix_task_facility ON tasks (facility_id, task_status);
CREATE INDEX ix_task_assignee ON tasks (assigned_to, task_status);

CREATE TABLE task_updates (
  update_id       NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_task_updates PRIMARY KEY,
  task_id         NUMBER        NOT NULL CONSTRAINT fk_tu_task REFERENCES tasks (task_id) ON DELETE CASCADE,
  user_id         NUMBER        CONSTRAINT fk_tu_user REFERENCES app_users (user_id),
  old_status      VARCHAR2(12),
  new_status      VARCHAR2(12)  NOT NULL,
  note            VARCHAR2(1000),
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_tu_task ON task_updates (task_id, created_at);

-- ============================================================================
-- 6. History: operational events (from the floor) and the audit trail (who changed what)
-- ============================================================================
CREATE TABLE operation_events (
  event_id        NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_operation_events PRIMARY KEY,
  facility_id     VARCHAR2(10)  NOT NULL CONSTRAINT fk_oe_facility REFERENCES facilities (facility_id),
  sim_time_s      NUMBER(7)     NOT NULL,
  message         VARCHAR2(300) NOT NULL,
  entity_kind     VARCHAR2(12),
  entity_id       VARCHAR2(20),
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_oe_facility ON operation_events (facility_id, event_id);

CREATE TABLE audit_log (
  audit_id        NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_audit_log PRIMARY KEY,
  user_id         NUMBER,                              -- NULL = system
  action          VARCHAR2(40)   NOT NULL,
  entity          VARCHAR2(40)   NOT NULL,
  entity_id       VARCHAR2(40),
  facility_id     VARCHAR2(10),
  details         VARCHAR2(2000),
  client_info     VARCHAR2(200),
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_facility ON audit_log (facility_id, audit_id);
CREATE INDEX ix_audit_user ON audit_log (user_id, audit_id);

-- Single-row table holding the operations clock and controls.
CREATE TABLE sim_state (
  state_id        NUMBER(1)     DEFAULT 1 CONSTRAINT pk_sim_state PRIMARY KEY,
  sim_time_s      NUMBER(12,3)  NOT NULL,
  real_time_s     NUMBER(14,3)  DEFAULT 0 NOT NULL,
  speed           NUMBER(3,1)   DEFAULT 1 NOT NULL,
  paused          CHAR(1)       DEFAULT 'N' NOT NULL,
  next_shipment   NUMBER(10)    NOT NULL,
  next_pallet     NUMBER(10)    NOT NULL,
  -- container terminal and store-delivery counters
  next_box             NUMBER(10)  DEFAULT 400000 NOT NULL,   -- next container serial number
  next_order           NUMBER(10)  DEFAULT 5000 NOT NULL,     -- next store order number
  port_moves_today     NUMBER(7)   DEFAULT 0 NOT NULL,
  port_calls_today     NUMBER(5)   DEFAULT 0 NOT NULL,
  port_gate_in_today   NUMBER(7)   DEFAULT 0 NOT NULL,
  port_gate_out_today  NUMBER(7)   DEFAULT 0 NOT NULL,
  port_ext_timer_s     NUMBER(8,2) DEFAULT 0 NOT NULL,
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by      NUMBER,
  CONSTRAINT ck_sim_single CHECK (state_id = 1),
  CONSTRAINT ck_sim_paused CHECK (paused IN ('Y', 'N')),
  CONSTRAINT ck_sim_speed  CHECK (speed IN (1, 2, 4))
);

-- ============================================================================
-- 7. The logistics park: tenant companies, their buildings, public traffic,
--    the two park gates and the import / export log of every truck through them
-- ============================================================================
CREATE TABLE park_companies (
  company_id      VARCHAR2(20)  CONSTRAINT pk_park_companies PRIMARY KEY,
  name            VARCHAR2(80)  NOT NULL CONSTRAINT uq_company_name UNIQUE,
  industry        VARCHAR2(60)  NOT NULL,
