  CONSTRAINT ck_gl_trade     CHECK (trade_type IN ('IMPORT', 'EXPORT', 'EMPTY')),
  CONSTRAINT ck_gl_gate_dir  CHECK ((gate_code = 'WEST' AND direction = 'IN') OR (gate_code = 'EAST' AND direction = 'OUT')),
  CONSTRAINT ck_gl_cargo     CHECK ((trade_type = 'IMPORT' AND direction = 'IN'  AND pallets > 0)
                                 OR (trade_type = 'EXPORT' AND direction = 'OUT' AND pallets > 0)
