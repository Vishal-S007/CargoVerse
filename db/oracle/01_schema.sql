-- ============================================================================
-- 8. The container port: shipping lines, berths, quay cranes, the ships that
--    call, every container move (ledger) and the boxes currently in the yard
-- ============================================================================
CREATE TABLE shipping_lines (
  line_code       VARCHAR2(3)   CONSTRAINT pk_shipping_lines PRIMARY KEY,
  name            VARCHAR2(60)  NOT NULL CONSTRAINT uq_line_name UNIQUE,
  owner_code      VARCHAR2(4)   NOT NULL CONSTRAINT uq_line_owner UNIQUE,   -- ISO 6346 owner code (line code + 'U')
  CONSTRAINT ck_line_code  CHECK (REGEXP_LIKE(line_code, '^[A-Z]{3}$')),
  CONSTRAINT ck_line_owner CHECK (owner_code = line_code || 'U')
);

CREATE TABLE port_berths (
  berth_code      VARCHAR2(4)   CONSTRAINT pk_port_berths PRIMARY KEY,
  name            VARCHAR2(40)  NOT NULL,
  building_id     VARCHAR2(20)  NOT NULL CONSTRAINT fk_berth_building REFERENCES park_buildings (building_id),
  pos_x           NUMBER(8,2)   NOT NULL,                 -- centre of the berth along the quay
  length_m        NUMBER(5)     DEFAULT 90 NOT NULL,
  is_open         CHAR(1)       DEFAULT 'Y' NOT NULL,
  vessel_id       VARCHAR2(10),                           -- ship alongside or cleared in (FK added below)
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_berth_open CHECK (is_open IN ('Y', 'N')),
  CONSTRAINT ck_berth_len  CHECK (length_m > 0)
);

CREATE TABLE vessels (
  vessel_id       VARCHAR2(10)  CONSTRAINT pk_vessels PRIMARY KEY,
  name            VARCHAR2(40)  NOT NULL CONSTRAINT uq_vessel_name UNIQUE,
  line_code       VARCHAR2(3)   NOT NULL CONSTRAINT fk_vessel_line REFERENCES shipping_lines (line_code),
  imo_no          VARCHAR2(11)  NOT NULL CONSTRAINT uq_vessel_imo UNIQUE,
  flag            VARCHAR2(30)  NOT NULL,
  hull_color      VARCHAR2(7)   NOT NULL,
  capacity_boxes  NUMBER(4)     NOT NULL,
  through_boxes   NUMBER(4)     DEFAULT 0 NOT NULL,       -- aboard for other ports
  anchor_slot     NUMBER(2)     NOT NULL CONSTRAINT uq_vessel_slot UNIQUE,
  origin_port     VARCHAR2(40)  NOT NULL,
  next_port       VARCHAR2(40)  NOT NULL,
  vessel_status   VARCHAR2(10)  NOT NULL,
  berth_code      VARCHAR2(4)   CONSTRAINT fk_vessel_berth REFERENCES port_berths (berth_code),
  voyage_no       VARCHAR2(6)   NOT NULL,
  calls_total     NUMBER(6)     DEFAULT 0 NOT NULL,
  import_boxes    NUMBER(4)     DEFAULT 0 NOT NULL,       -- still to discharge here
  export_boxes    NUMBER(4)     DEFAULT 0 NOT NULL,       -- loaded here this call
  export_target   NUMBER(4)     DEFAULT 0 NOT NULL,
  discharged      NUMBER(4)     DEFAULT 0 NOT NULL,
  loaded          NUMBER(4)     DEFAULT 0 NOT NULL,
  on_hold         CHAR(1)       DEFAULT 'N' NOT NULL,     -- held by the port manager
  waited_s        NUMBER(10,2)  DEFAULT 0 NOT NULL,
  timer_s         NUMBER(10,2)  DEFAULT 0 NOT NULL,
  leg_dist        NUMBER(10,3)  DEFAULT 0 NOT NULL,
  pos_x           NUMBER(10,3)  DEFAULT 0 NOT NULL,
  pos_z           NUMBER(10,3)  DEFAULT 0 NOT NULL,
  heading         NUMBER(10,5)  DEFAULT 0 NOT NULL,
  arrived_s       NUMBER(7),
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_vsl_imo    CHECK (REGEXP_LIKE(imo_no, '^IMO [0-9]{7}$')),
  CONSTRAINT ck_vsl_color  CHECK (REGEXP_LIKE(hull_color, '^#[0-9A-Fa-f]{6}$')),
  CONSTRAINT ck_vsl_status CHECK (vessel_status IN ('AT_SEA', 'ARRIVING', 'ANCHORED', 'BERTHING', 'BERTHED', 'DEPARTING')),
  CONSTRAINT ck_vsl_berth  CHECK (vessel_status IN ('AT_SEA', 'ARRIVING', 'ANCHORED') OR berth_code IS NOT NULL),
  CONSTRAINT ck_vsl_hold   CHECK (on_hold IN ('Y', 'N')),
  CONSTRAINT ck_vsl_boxes  CHECK (import_boxes >= 0 AND export_boxes >= 0 AND through_boxes + export_boxes <= capacity_boxes)
);
ALTER TABLE port_berths ADD CONSTRAINT fk_berth_vessel
  FOREIGN KEY (vessel_id) REFERENCES vessels (vessel_id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE quay_cranes (
  crane_id        VARCHAR2(6)   CONSTRAINT pk_quay_cranes PRIMARY KEY,
  berth_code      VARCHAR2(4)   NOT NULL CONSTRAINT fk_crane_berth REFERENCES port_berths (berth_code),
  offset_m        NUMBER(5,1)   NOT NULL,
  crane_phase     VARCHAR2(10)  DEFAULT 'IDLE' NOT NULL,
  cycle_pct       NUMBER(6,4)   DEFAULT 0 NOT NULL,
  moves_today     NUMBER(6)     DEFAULT 0 NOT NULL,
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_crane_phase CHECK (crane_phase IN ('IDLE', 'DISCHARGE', 'LOAD')),
  CONSTRAINT ck_crane_cycle CHECK (cycle_pct BETWEEN 0 AND 1)
);

-- One row per port call (written by wt_port.log_call when a ship berths and when it sails).
CREATE TABLE vessel_calls (
  call_id          NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_vessel_calls PRIMARY KEY,
  vessel_id        VARCHAR2(10)  NOT NULL CONSTRAINT fk_call_vessel REFERENCES vessels (vessel_id),
  voyage_no        VARCHAR2(6)   NOT NULL,
  berth_code       VARCHAR2(4)   NOT NULL CONSTRAINT fk_call_berth REFERENCES port_berths (berth_code),
  arrived_s        NUMBER(7)     NOT NULL,
  departed_s       NUMBER(7),
  boxes_discharged NUMBER(4)     DEFAULT 0 NOT NULL,
  boxes_loaded     NUMBER(4)     DEFAULT 0 NOT NULL,
  arrived_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  departed_at      TIMESTAMP,
  call_status      VARCHAR2(10)  GENERATED ALWAYS AS (CAST(CASE WHEN departed_at IS NULL THEN 'ALONGSIDE' ELSE 'COMPLETED' END AS VARCHAR2(10))) VIRTUAL,
  CONSTRAINT uq_call_voyage UNIQUE (vessel_id, voyage_no),
  CONSTRAINT ck_call_times  CHECK (departed_at IS NULL OR departed_at >= arrived_at)
);

CREATE TABLE yard_blocks (
  block_code      VARCHAR2(6)   CONSTRAINT pk_yard_blocks PRIMARY KEY,
  description     VARCHAR2(80)  NOT NULL,
  capacity_boxes  NUMBER(4)     NOT NULL,
  CONSTRAINT ck_block_code CHECK (block_code IN ('IMPORT', 'EXPORT')),
  CONSTRAINT ck_block_cap  CHECK (capacity_boxes > 0)
);

-- Container ledger: every lift on or off a ship and every box through the terminal gate.
-- trg_container_moves_ai keeps YARD_CONTAINERS in step with it.
CREATE TABLE container_moves (
  move_id         NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_container_moves PRIMARY KEY,
  container_no    VARCHAR2(11)  NOT NULL,
  line_code       VARCHAR2(3)   GENERATED ALWAYS AS (CAST(SUBSTR(container_no, 1, 3) AS VARCHAR2(3))) VIRTUAL
                                CONSTRAINT fk_move_line REFERENCES shipping_lines (line_code),
  move_type       VARCHAR2(9)   NOT NULL,
  vessel_id       VARCHAR2(10)  CONSTRAINT fk_move_vessel REFERENCES vessels (vessel_id),
  berth_code      VARCHAR2(4)   CONSTRAINT fk_move_berth REFERENCES port_berths (berth_code),
  crane_id        VARCHAR2(6)   CONSTRAINT fk_move_crane REFERENCES quay_cranes (crane_id),
  truck_id        VARCHAR2(20)  CONSTRAINT fk_move_truck REFERENCES trucks (truck_id),
  facility_id     VARCHAR2(10)  CONSTRAINT fk_move_facility REFERENCES facilities (facility_id),
  sim_time_s      NUMBER(7)     NOT NULL,
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_move_no   CHECK (REGEXP_LIKE(container_no, '^[A-Z]{3}U[0-9]{7}$')),
  CONSTRAINT ck_move_type CHECK (move_type IN ('DISCHARGE', 'LOAD', 'GATE_OUT', 'GATE_IN')),
  CONSTRAINT ck_move_ship CHECK ((move_type IN ('DISCHARGE', 'LOAD') AND vessel_id IS NOT NULL AND crane_id IS NOT NULL)
                              OR (move_type IN ('GATE_OUT', 'GATE_IN') AND vessel_id IS NULL AND crane_id IS NULL)),
  CONSTRAINT ck_move_truck CHECK (truck_id IS NULL OR facility_id IS NOT NULL)
);
CREATE INDEX ix_move_container ON container_moves (container_no, move_id);
CREATE INDEX ix_move_vessel ON container_moves (vessel_id, move_id);
CREATE INDEX ix_move_truck ON container_moves (truck_id);

-- Boxes in the stacks right now (maintained only by trg_container_moves_ai).
CREATE TABLE yard_containers (
  container_no    VARCHAR2(11)  CONSTRAINT pk_yard_containers PRIMARY KEY,
  block_code      VARCHAR2(6)   NOT NULL CONSTRAINT fk_yc_block REFERENCES yard_blocks (block_code),
  line_code       VARCHAR2(3)   NOT NULL CONSTRAINT fk_yc_line REFERENCES shipping_lines (line_code),
  vessel_id       VARCHAR2(10)  CONSTRAINT fk_yc_vessel REFERENCES vessels (vessel_id),     -- discharged from
  facility_id     VARCHAR2(10)  CONSTRAINT fk_yc_facility REFERENCES facilities (facility_id), -- delivered by
  arrived_move_id NUMBER        NOT NULL,   -- the CONTAINER_MOVES row that stacked it (set by the trigger)
  arrived_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_yc_block ON yard_containers (block_code, arrived_move_id);

-- ============================================================================
-- 9. Vendor stores in town, their shelf stock, the orders they place on the
--    CargoVerse warehouses and the delivery vans that restock them
-- ============================================================================
CREATE TABLE stores (
  store_id         VARCHAR2(8)   CONSTRAINT pk_stores PRIMARY KEY,
  building_id      VARCHAR2(20)  NOT NULL CONSTRAINT uq_store_building UNIQUE
                                 CONSTRAINT fk_store_building REFERENCES park_buildings (building_id),
  company_id       VARCHAR2(20)  NOT NULL CONSTRAINT fk_store_company REFERENCES park_companies (company_id),
  name             VARCHAR2(60)  NOT NULL,
  store_kind       VARCHAR2(12)  NOT NULL,
  facility_id      VARCHAR2(10)  NOT NULL CONSTRAINT fk_store_facility REFERENCES facilities (facility_id), -- usual supplier
  deliveries_today NUMBER(5)     DEFAULT 0 NOT NULL,
  updated_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_store_kind CHECK (store_kind IN ('SUPERMARKET', 'HARDWARE', 'OFFICE', 'PHARMACY', 'CONVENIENCE'))
);

CREATE TABLE store_stock (
  store_id        VARCHAR2(8)   NOT NULL CONSTRAINT fk_ss_store REFERENCES stores (store_id),
  sku_id          VARCHAR2(20)  NOT NULL CONSTRAINT fk_ss_sku REFERENCES skus (sku_id),
  units           NUMBER(6)     NOT NULL,
  reorder_at      NUMBER(6)     NOT NULL,
  max_units       NUMBER(6)     NOT NULL,
  sales_per_hour  NUMBER(6,1)   NOT NULL,
  sold_today      NUMBER(8)     DEFAULT 0 NOT NULL,
  stock_status    VARCHAR2(8)   GENERATED ALWAYS AS (CAST(CASE WHEN units = 0 THEN 'EMPTY' WHEN units <= reorder_at THEN 'REORDER' ELSE 'OK' END AS VARCHAR2(8))) VIRTUAL,
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_store_stock PRIMARY KEY (store_id, sku_id),
  CONSTRAINT ck_ss_units    CHECK (units >= 0),
  CONSTRAINT ck_ss_levels   CHECK (reorder_at >= 0 AND reorder_at < max_units),
  CONSTRAINT ck_ss_rate     CHECK (sales_per_hour >= 0)
);

CREATE TABLE delivery_vans (
  van_id          VARCHAR2(10)  CONSTRAINT pk_delivery_vans PRIMARY KEY,
  facility_id     VARCHAR2(10)  NOT NULL CONSTRAINT fk_van_facility REFERENCES facilities (facility_id),
  van_kind        VARCHAR2(9)   NOT NULL,
  plate           VARCHAR2(20)  NOT NULL CONSTRAINT uq_van_plate UNIQUE,
  driver_name     VARCHAR2(60)  NOT NULL,
  van_status      VARCHAR2(10)  DEFAULT 'IDLE' NOT NULL,
  order_id        VARCHAR2(12),                           -- current order (FK added below)
  store_id        VARCHAR2(8)   CONSTRAINT fk_van_store REFERENCES stores (store_id),
  leg_dist        NUMBER(10,3)  DEFAULT 0 NOT NULL,
  timer_s         NUMBER(8,2)   DEFAULT 0 NOT NULL,
  pos_x           NUMBER(10,3)  DEFAULT 0 NOT NULL,
  pos_z           NUMBER(10,3)  DEFAULT 0 NOT NULL,
  heading         NUMBER(10,5)  DEFAULT 0 NOT NULL,
  trips_today     NUMBER(5)     DEFAULT 0 NOT NULL,
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_van_kind   CHECK (van_kind IN ('VAN', 'BOX_TRUCK')),
  CONSTRAINT ck_van_status CHECK (van_status IN ('IDLE', 'LOADING', 'TO_STORE', 'UNLOADING', 'RETURNING')),
  CONSTRAINT ck_van_order  CHECK ((van_status = 'IDLE' AND order_id IS NULL) OR (van_status <> 'IDLE' AND order_id IS NOT NULL))
);

CREATE TABLE store_orders (
  order_id        VARCHAR2(12)  CONSTRAINT pk_store_orders PRIMARY KEY,
  store_id        VARCHAR2(8)   NOT NULL,
  sku_id          VARCHAR2(20)  NOT NULL,
  facility_id     VARCHAR2(10)  NOT NULL CONSTRAINT fk_so_facility REFERENCES facilities (facility_id),
  units           NUMBER(6)     NOT NULL,
  order_status    VARCHAR2(16)  DEFAULT 'PLACED' NOT NULL,
  order_source    VARCHAR2(6)   DEFAULT 'AUTO' NOT NULL,
  placed_by       NUMBER        CONSTRAINT fk_so_user REFERENCES app_users (user_id),
  van_id          VARCHAR2(10)  CONSTRAINT fk_so_van REFERENCES delivery_vans (van_id),
  placed_s        NUMBER(7)     NOT NULL,
  dispatched_s    NUMBER(7),
  delivered_s     NUMBER(7),
  placed_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  dispatched_at   TIMESTAMP,                              -- set by trg_store_orders_biu
  delivered_at    TIMESTAMP,
  -- a store can only order what it stocks (composite foreign key onto its shelf lines)
  CONSTRAINT fk_so_line    FOREIGN KEY (store_id, sku_id) REFERENCES store_stock (store_id, sku_id),
  CONSTRAINT ck_so_id      CHECK (REGEXP_LIKE(order_id, '^SO-[0-9]+$')),
  CONSTRAINT ck_so_units   CHECK (units > 0),
  CONSTRAINT ck_so_status  CHECK (order_status IN ('PLACED', 'LOADING', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED')),
  CONSTRAINT ck_so_source  CHECK (order_source IN ('AUTO', 'MANUAL')),
  CONSTRAINT ck_so_manual  CHECK (order_source = 'AUTO' OR placed_by IS NOT NULL),
  CONSTRAINT ck_so_van     CHECK (order_status IN ('PLACED', 'CANCELLED') OR van_id IS NOT NULL)
);
CREATE INDEX ix_so_store ON store_orders (store_id, placed_at);
CREATE INDEX ix_so_status ON store_orders (order_status);
ALTER TABLE delivery_vans ADD CONSTRAINT fk_van_order
  FOREIGN KEY (order_id) REFERENCES store_orders (order_id) DEFERRABLE INITIALLY DEFERRED;

