// Generates db/oracle/04_seed.sql from the application's seed data so the Oracle
// database starts in exactly the same state as the demo. Run: npm run db:gen-seed
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createSeedWorld, SKUS, seedGateHistory } from '../../src/data/seed';
import { PARK_COMPANIES, PARK_BUILDINGS, PARK_ROUTES, PARK_VEHICLES, PARK_GATES, gateBuildingId } from '../../src/data/park';
import { syncPoses } from '../../src/sim/engine';
import { LAYOUTS } from '../../src/data/layouts';
import { STORE_DEFS, VESSEL_LINES, vesselByPrefix, YARD_CAPACITY } from '../../src/data/city';
import {
  ROLES, PERMISSIONS, ROLE_PERMS, JOB_TITLES, EMPLOYEES, USERS, DEMO_PASSWORDS, FORKLIFT_OPERATORS, CARRIERS, carrierId, SEED_TASKS, LICENSES,
} from './people';
import { hashPassword } from '../auth';

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: number | null | undefined, digits = 3) => (v === null || v === undefined || Number.isNaN(v) ? 'NULL' : String(Math.round(v * 10 ** digits) / 10 ** digits));
const yn = (b: boolean) => (b ? "'Y'" : "'N'");

const w = createSeedWorld();
syncPoses(w);
const out: string[] = [];
const line = (s = '') => out.push(s);

line('--------------------------------------------------------------------------------');
line('-- CargoVerse — seed data (GENERATED by server/db/gen-seed.ts — do not edit by hand)');
line('-- Demo sign-ins: admin / ' + DEMO_PASSWORDS.ADMIN + ' · alex.chen, meera.iyer / ' + DEMO_PASSWORDS.MANAGER +
  ' · zoe.reyes, dana.brooks, carla.mendes, sam.patel / ' + DEMO_PASSWORDS.OPERATOR);
line('--------------------------------------------------------------------------------');
line('SET DEFINE OFF');
line();
line('-- security');
for (const r of ROLES) line(`INSERT INTO roles (role_code, role_name, description) VALUES (${q(r.code)}, ${q(r.name)}, ${q(r.description)});`);
for (const p of PERMISSIONS) line(`INSERT INTO permissions (perm_code, description) VALUES (${q(p.code)}, ${q(p.description)});`);
for (const [role, perms] of Object.entries(ROLE_PERMS)) for (const p of perms) line(`INSERT INTO role_permissions (role_code, perm_code) VALUES (${q(role)}, ${q(p)});`);
for (const j of JOB_TITLES) line(`INSERT INTO job_titles (job_code, title, responsibilities) VALUES (${q(j.code)}, ${q(j.title)}, ${q(j.responsibilities)});`);

line();
line('-- facilities (stock starts at 0; the OPENING stock movements below set it through the trigger)');
for (const f of Object.values(w.facilities)) {
  line(`INSERT INTO facilities (facility_id, name, short_name, facility_kind, address, capacity_pallets, stock_pallets, stock_start_pallets, outbound_today, putaways_today, otd_prev_pct, trucks_on_site_start)
  VALUES (${q(f.id)}, ${q(f.name)}, ${q(f.shortName)}, ${q(f.kindLabel)}, ${q(f.address)}, ${f.capacity}, 0, ${f.stockStart}, ${f.outboundToday}, ${f.putawaysToday}, ${n(f.otdPrevPct, 2)}, ${f.trucksOnSiteStart});`);
}

line();
line('-- people');
for (const e of EMPLOYEES) {
  line(`INSERT INTO employees (employee_id, full_name, email, phone, job_code, facility_id, hired_on) VALUES (${e.id}, ${q(e.name)}, ${q(e.email)}, ${q(e.phone)}, ${q(e.job)}, ${q(e.facility)}, DATE '${e.hired}');`);
}
for (const u of USERS) {
  line(`INSERT INTO app_users (user_id, username, password_hash, role_code, employee_id) VALUES (${u.id}, ${q(u.username)}, ${q(hashPassword(DEMO_PASSWORDS[u.role]))}, ${q(u.role)}, ${u.employeeId});`);
  for (const f of u.facilities) line(`INSERT INTO user_facility_access (user_id, facility_id) VALUES (${u.id}, ${q(f)});`);
}

line();
line('-- carriers, drivers, products, inventory');
for (const c of CARRIERS) line(`INSERT INTO carriers (carrier_id, name, display_name, phone) VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.display)}, ${q(c.phone)});`);
const trucks = Object.values(w.trucks);
trucks.forEach((t, i) => {
  line(`INSERT INTO drivers (driver_id, carrier_id, full_name, license_no) VALUES (${i + 1}, ${q(carrierId(t.carrier))}, ${q(t.driver)}, ${q(LICENSES[t.id] ?? `LIC-${t.id}`)});`);
});
for (const s of Object.values(SKUS)) {
  line(`INSERT INTO skus (sku_id, name, category, units_per_pallet, kg_per_pallet, pallet_look, icon) VALUES (${q(s.id)}, ${q(s.name)}, ${q(s.category)}, ${s.unitsPerPallet}, ${s.kgPerPallet}, ${q(s.look)}, ${q(s.icon)});`);
}
for (const f of Object.values(w.facilities)) {
  f.inventory.forEach((l, i) => line(`INSERT INTO inventory (facility_id, sku_id, units, reorder_level, display_order) VALUES (${q(f.id)}, ${q(l.skuId)}, ${l.units}, ${l.lowBelow}, ${i + 1});`));
  line(`INSERT INTO stock_movements (facility_id, sku_id, pallets_delta, units_delta, reason, sim_time_s) VALUES (${q(f.id)}, NULL, ${f.stock}, 0, 'OPENING', ${Math.round(w.simTime)});`);
}

line();
line('-- docks and chargers');
for (const d of Object.values(w.docks)) {
  line(`INSERT INTO docks (dock_id, facility_id, dock_name, dock_kind, description, truck_id, trucks_today) VALUES (${q(d.id)}, ${q(d.facilityId)}, ${q(d.name)}, ${q(d.kind.toUpperCase())}, ${q(d.description)}, ${q(d.truckId)}, ${d.trucksToday});`);
}
for (const c of Object.values(w.chargers)) {
  line(`INSERT INTO chargers (charger_id, facility_id, description, sessions_today, energy_kwh, rate_pct_min) VALUES (${q(c.id)}, ${q(c.facilityId)}, ${q(c.description)}, ${c.sessionsToday}, ${n(c.energyKwh, 2)}, ${c.ratePctPerMin});`);
}

line();
line('-- trucks, current shipments, forklifts, pallets (live positions from the operations model)');
trucks.forEach((t, i) => {
  line(`INSERT INTO trucks (truck_id, carrier_id, driver_id, plate, facility_id, direction, capacity_pallets, cargo_pallets, status, dock_id, current_shipment_id, sku_id, forklift_id, leg_idx, leg_dist, pos_x, pos_z, heading, speed, away_remaining_s)
  VALUES (${q(t.id)}, ${q(carrierId(t.carrier))}, ${i + 1}, ${q(t.plate)}, ${q(t.facilityId)}, ${q(t.direction.toUpperCase())}, ${t.capacity}, ${t.cargo}, ${q(t.phase.toUpperCase())}, ${q(t.dockId)}, ${q(t.shipmentId)}, ${q(t.skuId)}, ${q(t.forkliftId)}, ${t.legIdx}, ${n(t.legDist)}, ${n(t.pos.x)}, ${n(t.pos.z)}, ${n(t.heading, 5)}, ${n(t.speed)}, 0);`);
});
for (const s of Object.values(w.shipments)) {
  line(`INSERT INTO shipments (shipment_id, truck_id, facility_id, direction, customer, destination, sku_id, pallets, confirmed_s, picked_s, loaded_s, transit_s, delivered_s, promised_s, transit_minutes)
  VALUES (${q(s.id)}, ${q(s.truckId)}, ${q(s.facilityId)}, ${q(s.direction.toUpperCase())}, ${q(s.customer)}, ${q(s.destination)}, ${q(s.skuId)}, ${s.pallets}, ${s.confirmedAt}, ${s.pickedAt}, ${n(s.loadedAt, 0)}, ${n(s.transitAt, 0)}, ${n(s.deliveredAt, 0)}, ${s.promisedAt}, ${s.transitMinutes});`);
}
for (const f of Object.values(w.forklifts)) {
  line(`INSERT INTO forklifts (forklift_id, facility_id, model, operator_id, charger_id, battery_pct, task_state, truck_id, pallet_id, moves_today, pos_x, pos_z, heading, timer_s, pick_json, drop_json)
  VALUES (${q(f.id)}, ${q(f.facilityId)}, ${q(f.model)}, ${FORKLIFT_OPERATORS[f.id] ?? 'NULL'}, ${q(f.chargerId)}, ${n(f.battery, 2)}, ${q(f.task.toUpperCase())}, ${q(f.truckId)}, ${q(f.palletId)}, ${f.movesToday}, ${n(f.pos.x)}, ${n(f.pos.z)}, ${n(f.heading, 5)}, ${n(f.timer)}, ${q(f.pick ? JSON.stringify(f.pick) : null)}, ${q(f.drop ? JSON.stringify(f.drop) : null)});`);
}
for (const p of Object.values(w.pallets)) {
  line(`INSERT INTO pallets (pallet_id, facility_id, sku_id, qty, weight_kg, lot_no, received_label, yard_slot, forklift_id, is_featured, is_reserved)
  VALUES (${q(p.id)}, ${q(p.facilityId)}, ${q(p.skuId)}, ${p.qty}, ${p.weightKg}, ${q(p.lot)}, ${q(p.received)}, ${p.slot === null ? 'NULL' : p.slot}, ${q(p.forkliftId)}, ${yn(p.featured)}, ${yn(p.reserved)});`);
}

line();
line('-- the logistics park: tenants, buildings, roads, public traffic and the two gates');
for (const c of PARK_COMPANIES) {
  line(`INSERT INTO park_companies (company_id, name, industry, contact_name, contact_email, phone, brand_color, is_operator) VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.industry)}, ${q(c.contactName)}, ${q(c.email)}, ${q(c.phone)}, ${q(c.color)}, ${yn(c.isOperator)});`);
}
for (const b of PARK_BUILDINGS) {
  line(`INSERT INTO park_buildings (building_id, company_id, facility_id, name, building_kind, street, pos_x, pos_z, width_m, depth_m, height_m, rotation_deg, floors, staff_count, bldg_status, lease_start, lease_end, description)
  VALUES (${q(b.id)}, ${q(b.companyId)}, ${q(b.facilityId)}, ${q(b.name)}, ${q(b.kind)}, ${q(b.street)}, ${n(b.x, 2)}, ${n(b.z, 2)}, ${n(b.w, 1)}, ${n(b.d, 1)}, ${n(b.h, 1)}, ${b.rotation}, ${b.floors}, ${b.staff}, ${q(b.status)}, DATE '${b.leaseStart}', DATE '${b.leaseEnd}', ${q(b.description)});`);
}
for (const r of Object.values(PARK_ROUTES)) {
  line(`INSERT INTO park_routes (route_code, route_name, is_loop, length_m) VALUES (${q(r.code)}, ${q(r.name)}, ${yn(r.loop)}, ${n(r.length, 1)});`);
}
for (const v of PARK_VEHICLES) {
  line(`INSERT INTO park_vehicles (vehicle_id, company_id, vehicle_kind, plate, color_hex, route_code, speed_kmh, route_offset) VALUES (${q(v.id)}, ${q(v.companyId)}, ${q(v.kind)}, ${q(v.plate)}, ${q(v.color)}, ${q(v.route)}, ${v.speedKmh}, ${n(v.offset, 4)});`);
}
for (const g of Object.values(PARK_GATES)) {
  line(`INSERT INTO park_gates (gate_code, name, building_id, purpose) VALUES (${q(g.code)}, ${q(g.name)}, ${q(gateBuildingId(g.code))}, ${q(g.purpose)});`);
}
line();
line("-- earlier gate traffic today (trg_gate_log_ai turns these rows into the facilities' import/export counters)");
for (const r of seedGateHistory(w)) {
  line(`INSERT INTO park_gate_log (gate_code, direction, trade_type, truck_id, facility_id, shipment_id, sku_id, pallets, sim_time_s, created_at) VALUES (${q(r.gate)}, ${q(r.direction)}, ${q(r.trade)}, ${q(r.truckId)}, ${q(r.facilityId)}, NULL, ${r.trade === 'EMPTY' ? 'NULL' : q(r.skuId)}, ${r.pallets}, ${Math.round(r.simTime)}, SYSTIMESTAMP - NUMTODSINTERVAL(${r.minutesAgo}, 'MINUTE'));`);
}

line();
line('-- the container port: lines, berths, ships, quay cranes and the boxes already in the yard');
for (const l of VESSEL_LINES) line(`INSERT INTO shipping_lines (line_code, name, owner_code) VALUES (${q(l.code)}, ${q(l.name)}, ${q(l.code + 'U')});`);
const P = w.port;
for (const b of Object.values(P.berths)) {
  line(`INSERT INTO port_berths (berth_code, name, building_id, pos_x, length_m, is_open, vessel_id) VALUES (${q(b.id)}, ${q(b.name)}, 'PB-PORT', ${n(b.x, 2)}, 90, ${yn(b.open)}, ${q(b.vesselId)});`);
}
for (const v of Object.values(P.vessels)) {
  line(`INSERT INTO vessels (vessel_id, name, line_code, imo_no, flag, hull_color, capacity_boxes, through_boxes, anchor_slot, origin_port, next_port, vessel_status, berth_code, voyage_no, calls_total, import_boxes, export_boxes, export_target, discharged, loaded, on_hold, waited_s, timer_s, leg_dist, pos_x, pos_z, heading, arrived_s)
  VALUES (${q(v.id)}, ${q(v.name)}, ${q(v.prefix)}, ${q(v.imo)}, ${q(v.flag)}, ${q(v.color)}, ${v.capacity}, ${v.through}, ${v.slot}, ${q(v.origin)}, ${q(v.nextPort)}, ${q(v.status)}, ${q(v.berthId)}, ${q(v.voyage)}, ${v.calls}, ${v.importBoxes}, ${v.exportBoxes}, ${v.exportTarget}, ${v.discharged}, ${v.loaded}, ${yn(v.hold)}, ${n(v.waited, 2)}, ${n(v.timer, 2)}, ${n(v.dist)}, ${n(v.pos.x)}, ${n(v.pos.z)}, ${n(v.heading, 5)}, ${v.arrivedAt === null ? 'NULL' : Math.round(v.arrivedAt)});`);
}
for (const c of Object.values(P.cranes)) {
  line(`INSERT INTO quay_cranes (crane_id, berth_code, offset_m, crane_phase, cycle_pct, moves_today) VALUES (${q(c.id)}, ${q(c.berthId)}, ${n(c.offset, 1)}, ${q(c.phase.toUpperCase())}, ${n(c.cycle, 4)}, ${c.movesToday});`);
}
for (const v of Object.values(P.vessels)) {
  if (v.status === 'BERTHED' && v.berthId) line(`INSERT INTO vessel_calls (vessel_id, voyage_no, berth_code, arrived_s, arrived_at) VALUES (${q(v.id)}, ${q(v.voyage)}, ${q(v.berthId)}, ${Math.round(v.arrivedAt ?? w.simTime)}, SYSTIMESTAMP - INTERVAL '40' MINUTE);`);
}
line(`INSERT INTO yard_blocks (block_code, description, capacity_boxes) VALUES ('IMPORT', 'Import stack: discharged boxes waiting for a truck', ${YARD_CAPACITY});`);
line(`INSERT INTO yard_blocks (block_code, description, capacity_boxes) VALUES ('EXPORT', 'Export stack: boxes waiting for a ship', ${YARD_CAPACITY});`);
line('-- (trg_container_moves_ai stacks each of these boxes in YARD_CONTAINERS)');
P.importStack.forEach((no, i) => {
  const v = vesselByPrefix(no);
  const vessel = v ? Object.values(P.vessels).find((x) => x.prefix === v.prefix) : undefined;
  const crane = vessel?.berthId ? Object.values(P.cranes).find((c) => c.berthId === vessel.berthId)?.id ?? 'QC-01' : 'QC-01';
  line(`INSERT INTO container_moves (container_no, move_type, vessel_id, berth_code, crane_id, sim_time_s, created_at) VALUES (${q(no)}, 'DISCHARGE', ${q(vessel?.id ?? 'VSL-01')}, ${q(vessel?.berthId ?? 'B1')}, ${q(crane)}, ${Math.round(w.simTime - 3600 + i * 60)}, SYSTIMESTAMP - NUMTODSINTERVAL(${90 - i * 2}, 'MINUTE'));`);
});
P.exportStack.forEach((no, i) => {
  line(`INSERT INTO container_moves (container_no, move_type, sim_time_s, created_at) VALUES (${q(no)}, 'GATE_IN', ${Math.round(w.simTime - 2400 + i * 60)}, SYSTIMESTAMP - NUMTODSINTERVAL(${70 - i * 2}, 'MINUTE'));`);
});

line();
line('-- vendor stores in town, their shelves and the CargoVerse delivery fleet');
for (const d of STORE_DEFS) {
  const st = w.retail.stores[d.id];
  const b = PARK_BUILDINGS.find((x) => x.id === d.buildingId)!;
  line(`INSERT INTO stores (store_id, building_id, company_id, name, store_kind, facility_id, deliveries_today) VALUES (${q(d.id)}, ${q(d.buildingId)}, ${q(b.companyId)}, ${q(d.name)}, ${q(d.kind)}, ${q(d.facilityId)}, ${st.deliveriesToday});`);
  for (const l of st.lines) {
    line(`INSERT INTO store_stock (store_id, sku_id, units, reorder_at, max_units, sales_per_hour, sold_today) VALUES (${q(d.id)}, ${q(l.skuId)}, ${l.units}, ${l.reorderAt}, ${l.maxUnits}, ${n(l.salesPerHour, 1)}, ${l.soldToday});`);
  }
}
for (const v of Object.values(w.retail.vans)) {
  line(`INSERT INTO delivery_vans (van_id, facility_id, van_kind, plate, driver_name, van_status, pos_x, pos_z, heading, trips_today) VALUES (${q(v.id)}, ${q(v.facilityId)}, ${q(v.kind)}, ${q(v.plate)}, ${q(v.driver)}, ${q(v.status)}, ${n(v.pos.x)}, ${n(v.pos.z)}, ${n(v.heading, 5)}, ${v.tripsToday});`);
}

line();
line('-- operations clock and recent floor events');
line(`INSERT INTO sim_state (state_id, sim_time_s, real_time_s, speed, paused, next_shipment, next_pallet, next_box, next_order, port_moves_today, port_calls_today, port_gate_in_today, port_gate_out_today)
  VALUES (1, ${n(w.simTime)}, 0, 1, 'N', ${w.nextShipment}, ${w.nextPallet}, ${P.nextBox}, ${w.retail.nextOrder}, ${P.movesToday}, ${P.callsToday}, ${P.gateInToday}, ${P.gateOutToday});`);
for (const e of w.events.slice().reverse()) {
  line(`INSERT INTO operation_events (facility_id, sim_time_s, message, entity_kind, entity_id) VALUES (${q(e.facilityId)}, ${Math.round(e.t)}, ${q(e.text)}, ${q(e.ref?.kind)}, ${q(e.ref?.id)});`);
}

line();
line('-- 30 days of delivered shipments per facility (drives the on-time delivery KPI)');
const hist = Object.values(w.facilities).map((f) => {
  const truck = trucks.find((t) => t.facilityId === f.id)!;
  return `SELECT ${q(f.id)} AS fac, ${f.deliveries30d} AS total, ${f.onTime30d} AS ok, ${q(truck.id)} AS truck, ${q(f.inventory[0].skuId)} AS sku FROM dual`;
}).join('\n           UNION ALL ');
line(`BEGIN
  FOR f IN (${hist}) LOOP
    FOR i IN 1 .. f.total LOOP
      INSERT INTO shipments (shipment_id, truck_id, facility_id, direction, customer, destination, sku_id, pallets,
                             confirmed_s, picked_s, loaded_s, transit_s, delivered_s, promised_s, transit_minutes, on_time, created_at, delivered_ts)
      VALUES ('H' || SUBSTR(f.fac, 4) || '-' || LPAD(i, 5, '0'), f.truck, f.fac,
              CASE WHEN MOD(i, 2) = 0 THEN 'OUTBOUND' ELSE 'INBOUND' END,
              CASE MOD(i, 5) WHEN 0 THEN 'Liberty Supply Co.' WHEN 1 THEN 'Harbor & Co.' WHEN 2 THEN 'Metro Office Supply'
                             WHEN 3 THEN 'Hudson Clinics' ELSE 'Bayview Foods' END,
              'Historical delivery', f.sku, 6, 25200, 28800, 32400, 34200,
              CASE WHEN i <= f.ok THEN 36000 ELSE 39600 END, 37800, 30,
              CASE WHEN i <= f.ok THEN 'Y' ELSE 'N' END,
              SYSTIMESTAMP - NUMTODSINTERVAL(MOD(i * 7, 29) + 1, 'DAY'),
              SYSTIMESTAMP - NUMTODSINTERVAL(MOD(i * 7, 29) + 1, 'DAY') + INTERVAL '3' HOUR);
    END LOOP;
  END LOOP;
END;
/`);

line();
line('-- work already planned by the managers (audit trail attributed to the creating manager)');
SEED_TASKS.forEach((t, i) => {
  const id = i + 1;
  const status = t.status;
  line(`BEGIN DBMS_SESSION.SET_IDENTIFIER('${t.createdBy}'); END;
/`);
  line(`INSERT INTO tasks (task_id, facility_id, title, description, task_type, priority, task_status, source, assigned_to, created_by, truck_id, dock_id, due_at)
  VALUES (${id}, ${q(t.facility)}, ${q(t.title)}, ${q(t.description)}, ${q(t.type)}, ${q(t.priority)}, ${q(status)}, 'MANUAL', ${t.assignee ?? 'NULL'}, ${t.createdBy}, ${q(t.truck)}, ${q(t.dock)}, SYSTIMESTAMP + NUMTODSINTERVAL(${t.dueMinutes}, 'MINUTE'));`);
  line(`INSERT INTO task_updates (task_id, user_id, old_status, new_status, note) VALUES (${id}, ${t.createdBy}, NULL, ${q(t.assignee ? 'ASSIGNED' : 'OPEN')}, 'Task created');`);
  if (status !== 'ASSIGNED' && status !== 'OPEN') {
    const assigneeUser = USERS.find((u) => u.employeeId === t.assignee);
    line(`INSERT INTO task_updates (task_id, user_id, old_status, new_status, note) VALUES (${id}, ${assigneeUser?.id ?? 'NULL'}, 'ASSIGNED', ${q(status)}, ${q(t.note ?? null)});`);
  }
});
line(`BEGIN DBMS_SESSION.CLEAR_IDENTIFIER; END;
/`);
line();
line('COMMIT;');
line();
line('-- continue identity numbering after the explicit seed ids');
for (const [table, col] of [['employees', 'employee_id'], ['app_users', 'user_id'], ['drivers', 'driver_id'], ['tasks', 'task_id']]) {
  line(`ALTER TABLE ${table} MODIFY ${col} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);`);
}

// sanity: the layout must define every charger used by forklifts
for (const f of Object.values(w.forklifts)) if (!LAYOUTS[f.facilityId].chargers[f.chargerId]) throw new Error(`missing charger ${f.chargerId}`);

const file = resolve(process.cwd(), 'db/oracle/04_seed.sql');
writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${file} (${out.length} lines)`);
