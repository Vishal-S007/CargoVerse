// Generates db/oracle/11_wms_seed.sql (the Smart Warehouse reference data) from the same
// definitions the application uses, so bins and aisles in Oracle match the 3D view exactly.
// Called by gen-seed.ts (npm run db:gen-seed).
import type { WorldState } from '../../src/data/types';
import { SKUS } from '../../src/data/seed';
import { STORE_DEFS } from '../../src/data/city';
import { SKU_HANDLING, siteStorage, sensorDefs, demandHistory, DAMAGE_SEEDS, WMS_FACILITIES } from '../../src/data/wms';

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v === null || v === undefined ? 'NULL' : String(Math.round(v * 100) / 100));

export const REPORTERS: Record<string, string> = { 'WH-01': 'Dana Brooks', 'WH-02': 'Carla Mendes', 'WH-04': 'Zoe Reyes' };

/** INSERT ALL in chunks (one round trip per chunk when run by the setup script). */
function insertAll(table: string, cols: string, rows: string[], chunk = 80): string[] {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += chunk) {
    out.push('INSERT ALL');
    for (const r of rows.slice(i, i + chunk)) out.push(`  INTO ${table} (${cols}) VALUES (${r})`);
    out.push('SELECT 1 FROM dual;');
  }
  return out;
}

export function wmsSeedSql(w: WorldState): string {
  const out: string[] = [];
  const line = (s = '') => out.push(s);
  line('--------------------------------------------------------------------------------');
  line('-- CargoVerse — Smart Warehouse reference data (GENERATED by server/db/gen-wms-seed.ts — do not edit)');
  line('-- Racks, bins and the aisle graph of each building, product handling rules, sensors,');
  line('-- 90 days of demand history (dates relative to today) and sample damage reports.');
  line('-- Lots and bin contents are created from the current inventory when the server first starts.');
  line('--------------------------------------------------------------------------------');
  line('SET DEFINE OFF');
  line();
  line('-- the cold-chain product (databases created before it existed get it here)');
  const ins = SKUS['MED-INS'];
  line(`MERGE INTO skus d USING (SELECT ${q(ins.id)} AS sku_id FROM dual) s ON (d.sku_id = s.sku_id)
WHEN NOT MATCHED THEN INSERT (sku_id, name, category, units_per_pallet, kg_per_pallet, pallet_look, icon)
VALUES (${q(ins.id)}, ${q(ins.name)}, ${q(ins.category)}, ${ins.unitsPerPallet}, ${ins.kgPerPallet}, ${q(ins.look)}, ${q(ins.icon)});`);
  for (const f of Object.values(w.facilities)) {
    f.inventory.forEach((l, i) => {
      if (l.skuId !== 'MED-INS') return;
      line(`MERGE INTO inventory d USING (SELECT ${q(f.id)} AS facility_id, ${q(l.skuId)} AS sku_id FROM dual) s
   ON (d.facility_id = s.facility_id AND d.sku_id = s.sku_id)
WHEN NOT MATCHED THEN INSERT (facility_id, sku_id, units, reorder_level, display_order) VALUES (${q(f.id)}, ${q(l.skuId)}, ${l.units}, ${l.lowBelow}, ${i + 1});`);
    });
  }
  for (const d of STORE_DEFS) {
    for (const [skuId, maxUnits, reorderAt, perHour, units] of d.lines) {
      if (skuId !== 'MED-INS') continue;
      line(`MERGE INTO store_stock d USING (SELECT ${q(d.id)} AS store_id, ${q(skuId)} AS sku_id FROM dual) s
   ON (d.store_id = s.store_id AND d.sku_id = s.sku_id)
WHEN NOT MATCHED THEN INSERT (store_id, sku_id, units, reorder_at, max_units, sales_per_hour, sold_today) VALUES (${q(d.id)}, ${q(skuId)}, ${units}, ${reorderAt}, ${maxUnits}, ${n(perHour)}, 0);`);
    }
  }
  line();
  line('-- product handling rules');
  for (const h of Object.values(SKU_HANDLING)) {
    line(`INSERT INTO sku_handling (sku_id, shelf_life_days, temp_zone, min_c, max_c, lead_time_days, unit_cost, order_cost, supplier, description)
VALUES (${q(h.skuId)}, ${n(h.shelfLifeDays)}, ${q(h.tempZone)}, ${n(h.minC)}, ${n(h.maxC)}, ${h.leadTimeDays}, ${n(h.unitCost)}, ${n(h.orderCost)}, ${q(h.supplier)}, ${q(h.description)});`);
  }
  line();
  line('-- the aisle network (graph) and the bins of each building');
  for (const fac of WMS_FACILITIES) {
    const s = siteStorage(fac);
    line(`-- ${fac}: ${s.aisles.length} aisles × ${s.bays.length} bays × 2 sides × 3 levels = ${s.bins.length} bins`);
    out.push(...insertAll('wh_nodes', 'node_id, facility_id, node_kind, pos_x, pos_z, node_label',
      s.nodes.map((x) => `${q(x.id)}, ${q(fac)}, ${q(x.kind)}, ${n(x.x)}, ${n(x.z)}, ${q(x.label)}`)));
    out.push(...insertAll('wh_edges', 'edge_id, facility_id, from_node, to_node, metres',
      s.edges.map((e) => `${fac === 'WH-01' ? 10000 + e.id : fac === 'WH-02' ? 20000 + e.id : 40000 + e.id}, ${q(fac)}, ${q(e.from)}, ${q(e.to)}, ${n(e.metres)}`)));
    out.push(...insertAll('storage_bins', 'bin_id, facility_id, aisle, bay, rack_side, lvl, pos_x, pos_z, node_id, temp_zone, dock_metres',
      s.bins.map((b) => `${q(b.id)}, ${q(fac)}, ${q(b.aisle)}, ${b.bay}, ${q(b.side)}, ${b.level}, ${n(b.x)}, ${n(b.z)}, ${q(b.nodeId)}, ${q(b.zone)}, ${n(b.dockMetres)}`)));
    line(`INSERT INTO wms_settings (facility_id, putaway_policy) VALUES (${q(fac)}, 'RANDOM');`);
  }
  line();
  line('-- temperature sensors');
  for (const s of sensorDefs()) {
    line(`INSERT INTO sensors (sensor_id, facility_id, temp_zone, sensor_label, min_c, max_c, setpoint_c, pos_x, pos_z)
VALUES (${q(s.id)}, ${q(s.facilityId)}, ${q(s.zone)}, ${q(s.label)}, ${n(s.minC)}, ${n(s.maxC)}, ${n(s.setpoint)}, ${n(s.x)}, ${n(s.z)});`);
  }
  line();
  line('-- 90 days of demand per site and product (relative to the day the script runs)');
  const rows: string[] = [];
  for (const f of Object.values(w.facilities)) {
    for (const l of f.inventory) {
      for (const d of demandHistory(f.id, l.skuId, 90, l.units)) rows.push(`${q(f.id)}, ${q(l.skuId)}, TRUNC(SYSDATE) - ${d.daysAgo}, ${d.units}, ${d.picks}`);
    }
  }
  out.push(...insertAll('sku_daily_demand', 'facility_id, sku_id, demand_date, units_out, picks', rows, 100));
  line();
  line('-- damage reports (embeddings are added by the server)');
  for (const d of DAMAGE_SEEDS) {
    line(`INSERT INTO damage_reports (facility_id, sku_id, severity, report_text, reported_by, created_at)
VALUES (${q(d.facilityId)}, ${q(d.skuId)}, ${q(d.severity)}, ${q(d.text)}, ${q(REPORTERS[d.facilityId])}, SYSTIMESTAMP - NUMTODSINTERVAL(${d.daysAgo * 24 + 3}, 'HOUR'));`);
  }
  line('COMMIT;');
  return out.join('\n') + '\n';
}
